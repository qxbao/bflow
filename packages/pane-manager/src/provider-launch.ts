import { getRoleTopologySpec, type RoleSelector } from "./types.js";
import { readFile, open } from "node:fs/promises";
import { constants } from "node:fs";

export interface RoleMcpServer {
  readonly command: string;
  readonly args?: readonly string[];
  readonly env?: Readonly<Record<string, string>>;
}
export interface ProviderRoleLaunchOptions {
  readonly agentKind: "claude" | "codex";
  readonly role: RoleSelector;
  readonly systemPrompt: string;
  readonly model?: string;
  /** Operator-owned stdio servers, never a command supplied by an agent/repository. */
  readonly mcpServers?: Readonly<Record<string, RoleMcpServer>>;
  /** Already vetted, launch-local native SessionStart command. Does not install global hooks. */
  readonly nativeSessionHookCommand?: string;
}

export interface ProviderRoleLaunchFiles {
  readonly agentKind: "claude" | "codex";
  readonly role: RoleSelector;
  readonly systemPrompt: string;
  readonly model?: string;
  readonly mcpConfigFile: string;
  readonly hooksSettingsFile: string;
}

function toml(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(toml).join(",")}]`;
  if (value !== null && typeof value === "object")
    return `{${Object.entries(value).map(([key, item]) => `${JSON.stringify(key)}=${toml(item)}`).join(",")}}`;
  return JSON.stringify(value);
}

/** Roles that investigate read-only and may run the git reads below (mirrors the Runtime host guard). */
const INVESTIGATION_ROLES: ReadonlySet<string> = new Set(["planner", "specifier", "architect", "reviewer", "qa"]);
const READ_ONLY_GIT_PATTERNS = ["log", "show", "diff", "status", "branch"].map(command => `Bash(git ${command}:*)`);

/** Explicit opt-in policy for locally verified Claude/Codex CLI flags. Other kinds keep their own configuration. */
export function buildProviderRoleLaunch(options: ProviderRoleLaunchOptions): readonly string[] {
  const spec = getRoleTopologySpec(options.role);
  if (!spec) throw new Error(`Unsupported Bflow role: ${options.role}`);
  if (!options.systemPrompt.trim()) throw new Error("Role system prompt is required");
  if (options.agentKind !== "claude" && options.agentKind !== "codex") throw new Error("Provider launch policy supports Claude and Codex only");
  const servers = options.mcpServers ?? {};
  for (const [name, server] of Object.entries(servers)) {
    if (!/^[A-Za-z][A-Za-z0-9_-]*$/.test(name) || !server.command || server.command.includes("\0"))
      throw new Error("Invalid operator MCP server configuration");
  }
  const hook = options.nativeSessionHookCommand;
  if (hook?.includes("\0")) throw new Error("Native session hook cannot contain NUL");
  if (options.agentKind === "claude") {
    const settings = hook ? { hooks: { SessionStart: [{ hooks: [{ type: "command", command: hook, timeout: 10 }] }] } } : {};
    // Conversation and Coordinator get their scoped context through trusted host
    // tools; native repository reads would also expose host state/secrets.
    const tools = spec.topologyRole === "chat" || spec.topologyRole === "coordinator"
      ? "" : spec.readOnlyWorkspace ? "Read,Glob,Grep" : "Read,Glob,Grep,Edit,Write";
    // Read-only investigation roles may run git reads; dontAsk refuses every other Bash call, and the host guard re-checks each one.
    const gitReads = tools && INVESTIGATION_ROLES.has(options.role) ? READ_ONLY_GIT_PATTERNS : [];
    return ["--restricted", "--strict-mcp-config", "--setting-sources", "", "--disable-slash-commands",
      "--permission-mode", "dontAsk", "--tools", gitReads.length ? `${tools},Bash` : tools,
      "--allowedTools", [tools, ...gitReads, ...Object.keys(servers).map(name => `mcp__${name}__*`)].filter(Boolean).join(","),
      // Claude applies Read(path) to all read tools and Edit(path) to all file writes.
      "--disallowedTools", ["Read", "Edit"].flatMap(tool =>
        ["./.bflow/**", "./.git/**", "~/.claude/**", "~/.codex/**", "~/.ssh/**", "~/.aws/**", "~/.config/**"].map(pattern => `${tool}(${pattern})`)).join(","),
      "--settings", JSON.stringify(settings), "--mcp-config", JSON.stringify({ mcpServers: servers }),
      "--append-system-prompt", options.systemPrompt,
      ...(options.model ? ["--model", options.model] : [])];
  }
  const args = ["--no-daemon", "--sandbox", spec.readOnlyWorkspace ? "read-only" : "workspace-write",
    "--ask-for-approval", "never", "-c", `developer_instructions=${JSON.stringify(options.systemPrompt)}`,
    "-c", "web_search=\"disabled\"", "-c", `mcp_servers=${toml(servers)}`];
  if (hook) args.push("--enable", "hooks", "--dangerously-bypass-hook-trust", "-c",
    `hooks.SessionStart=${toml([{ hooks: [{ type: "command", command: hook, timeout: 10 }] }])}`);
  if (options.model) args.push("--model", options.model);
  return args;
}

/** Launch-local files are generated by the trusted host, never loaded from project agent output. */
export async function buildProviderRoleLaunchFromFiles(options: ProviderRoleLaunchFiles): Promise<readonly string[]> {
  const mcp = JSON.parse(await readFile(options.mcpConfigFile, "utf8"));
  const settings = JSON.parse(await readFile(options.hooksSettingsFile, "utf8"));
  if (!mcp || typeof mcp !== "object" || !mcp.mcpServers || typeof mcp.mcpServers !== "object" || Array.isArray(mcp.mcpServers))
    throw new Error("Trusted host MCP config must contain mcpServers");
  if (!settings || typeof settings !== "object" || !settings.hooks || typeof settings.hooks !== "object" || Array.isArray(settings.hooks))
    throw new Error("Trusted host settings must contain lifecycle hooks");
  const args = [...buildProviderRoleLaunch({ ...options, mcpServers: mcp.mcpServers })];
  const promptFile = options.mcpConfigFile + ".system-prompt.txt";
  const file = await open(promptFile, constants.O_WRONLY | constants.O_CREAT | constants.O_TRUNC | constants.O_NOFOLLOW, 0o600);
  try { await file.writeFile(options.systemPrompt); } finally { await file.close(); }
  if (options.agentKind === "claude") {
    args[args.indexOf("--mcp-config") + 1] = options.mcpConfigFile;
    args[args.indexOf("--settings") + 1] = options.hooksSettingsFile;
    // Herdr rejects multiline shell arguments. Claude's native file option also
    // keeps long role instructions out of the shell command line.
    const promptFlag = args.indexOf("--append-system-prompt");
    args[promptFlag] = "--append-system-prompt-file";
    args[promptFlag + 1] = promptFile;
  } else {
    // Native file loading replaces built-in instructions and avoids terminal line limits.
    // https://developers.openai.com/codex/config-reference#model_instructions_file
    const instructions = args.findIndex(value => value.startsWith("developer_instructions="));
    args[instructions] = `model_instructions_file=${JSON.stringify(promptFile)}`;
    args.push("--enable", "hooks", "--dangerously-bypass-hook-trust", "-c", `hooks=${toml(settings.hooks)}`);
  }
  return args;
}
