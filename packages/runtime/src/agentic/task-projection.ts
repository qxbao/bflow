import type { AcceptanceCriterion, Specification } from "@bflow/contracts";

/** Lenient object view: a draft without `metadata.sdd` or `conditionalTdd` projects with empty defaults. */
const record = (value: unknown): Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value) ? value as Record<string, unknown> : {};

const DOCUMENT_PATH = /\.(md|mdx|txt|rst|adoc)$/i;
const normalize = (path: string): string => path.replace(/\\/g, "/").replace(/^(?:\.\/)+/, "").replace(/\/+$/, "");
/** A planned path belongs to a task when it lies under an owned prefix, or an owned prefix lies under it (a directory it covers). */
function relatedToOwned(path: string, ownedPaths: readonly string[]): boolean {
  const value = normalize(path);
  return ownedPaths.some(owned => { const prefix = normalize(owned); return value === prefix || value.startsWith(`${prefix}/`) || prefix.startsWith(`${value}/`); });
}

/**
 * The specification input reviewed for one DAG task: its own criteria, traceability and conditional TDD assessment. A
 * submitted test strategy is narrowed to the same criteria; its other mappings belong to sibling tasks and would make
 * the task specification map criteria it does not contain. When `ownedPaths` is given, `affectedPaths` is narrowed to the
 * paths the task owns so a documentation task does not inherit sibling code paths.
 */
export function projectTaskSpecificationInput(draft: Specification, taskId: string, criteria: readonly AcceptanceCriterion[],
  specIdSuffix: string, conditionalTdd: unknown = draft.metadata?.conditionalTdd, ownedPaths?: readonly string[]): Specification {
  const ids = new Set(criteria.map(criterion => criterion.id));
  const sdd = record(draft.metadata?.sdd);
  const projectedSpecId = `${draft.specId}-${specIdSuffix}`;
  const affectedPaths = ownedPaths?.length ? draft.affectedPaths.filter(path => relatedToOwned(path, ownedPaths)) : draft.affectedPaths;
  return { ...draft, specId: projectedSpecId, acceptanceCriteria: [...criteria], traceabilityTaskIds: [taskId], affectedPaths,
    ...(draft.testStrategy ? { testStrategy: { ...draft.testStrategy, specId: projectedSpecId,
      tddDecision: { ...draft.testStrategy.tddDecision, specId: projectedSpecId, taskId },
      criterionMappings: draft.testStrategy.criterionMappings.filter(mapping => ids.has(mapping.criterionId)) } } : {}),
    ...(draft.tddDecision ? { tddDecision: { ...draft.tddDecision, specId: projectedSpecId, taskId } } : {}),
    metadata: { ...draft.metadata,
      sdd: { ...sdd, traceability: criteria.map(c => ({ criterionId: c.id, taskIds: [taskId] })) },
      conditionalTdd: { ...record(conditionalTdd), taskId } } } as Specification;
}

/** Surfaces whose verification methods apply only to tasks that own matching non-document files. */
const FILE_SURFACES = new Set(["infrastructure", "configuration", "ui_layout"]);
/**
 * The assessment a task is evaluated under. Methods generated by a file surface (infrastructure, configuration, UI)
 * belong to tasks that own non-document files; a task owning only documents drops those surfaces so it is not asked
 * for runners it has no code for. Behavioral assessments (domain logic, API, bugfix) and risk are never weakened.
 */
export function taskPolicyAssessment<T extends { taskType: string; changeImpact: Record<string, unknown>; testability: Record<string, unknown> }>(
  assessment: T, taskPaths: readonly string[]): T {
  if (!taskPaths.length || !taskPaths.every(path => DOCUMENT_PATH.test(normalize(path)))) return assessment;
  const surfaces = Array.isArray(assessment.changeImpact.surfaces) ? (assessment.changeImpact.surfaces as string[]).filter(surface => !FILE_SURFACES.has(surface)) : [];
  if (!FILE_SURFACES.has(assessment.taskType)) return { ...assessment, changeImpact: { ...assessment.changeImpact, surfaces: surfaces.length ? surfaces : [assessment.taskType] } };
  return { ...assessment, taskType: "documentation",
    changeImpact: { ...assessment.changeImpact, surfaces: surfaces.length ? surfaces : ["documentation"], behaviorChanged: false, deterministic: false, regressionReproducible: false, scope: "local" },
    testability: { level: "none", rationale: "Documentation-only task: no executable behavior is owned by this task." } };
}

/** Projects one DAG task with its own scoped paths and per-task assessment (an explicit task `conditionalTdd` always wins). */
export function projectDagTask(draft: Specification, task: { id: string; metadata?: Record<string, unknown> | undefined }, criteria: readonly AcceptanceCriterion[],
  specIdSuffix: string, ownedPaths: readonly string[]): Specification {
  const scoped = projectTaskSpecificationInput(draft, task.id, criteria, specIdSuffix, undefined, ownedPaths);
  const explicit = task.metadata?.conditionalTdd;
  if (explicit !== undefined) return projectTaskSpecificationInput(draft, task.id, criteria, specIdSuffix, explicit, ownedPaths);
  const base = record(draft.metadata?.conditionalTdd);
  const assessed = typeof base.taskType === "string" && typeof base.changeImpact === "object" && typeof base.testability === "object"
    ? taskPolicyAssessment(base as never, scoped.affectedPaths) : base;
  return projectTaskSpecificationInput(draft, task.id, criteria, specIdSuffix, assessed, ownedPaths);
}
