export type SosProvider = "claude" | "codex" | "agy";
const SOS_PROVIDERS: readonly SosProvider[] = ["claude", "codex", "agy"];
const CONFIG_FILES = [".bflow/config.yml", ".bflow/config.yaml", ".bflow/config.json"];

/** Effective `role: sos` launch selection from `.bflow/config.yml`; `source` says whether an explicit entry existed. */
export interface SosRoleConfig {
  readonly provider: SosProvider;
  readonly model?: string;
  readonly effort?: string;
  readonly profileName?: string;
  readonly fallbackCli?: SosProvider;
  readonly source: "config" | "default";
  readonly configPath?: string;
}

export interface SpawnSosAgentOptions {
  /** Host state directory (`configuration.directory`); SOS context lands in `<directory>/sos/`. */
  readonly directory: string;
  readonly repositoryPath: string;
  readonly sessionId: string;
  readonly herdrBinary: string;
  readonly manifest: SessionManifest | undefined;
  readonly turn: TrustedConversationTurn;
  readonly activityLog: TaskActivityLog;
  readonly runtimeSnapshot?: unknown;
  readonly schedulerError?: string | undefined;
  readonly inboundError?: string | undefined;
  readonly defaultProvider: string;
  /** Pre-generated by a caller that reports the name before the spawn finishes (see `newSosAgentName`). */
  readonly agentName?: string;
  /** Runs `herdr --session <sessionId> ...args` and returns stdout; throws on a non-zero exit. */
  readonly herdr: (args: string[]) => Promise<string>;
}

export interface SpawnedSosAgentResult {
  readonly ok: true;
  readonly value: {
    readonly agentName: string;
    readonly provider: SosProvider;
    readonly model?: string;
    readonly tabId: string;
    readonly paneId: string;
    readonly sosDirectory: string;
    readonly contextPath: string;
    readonly systemPromptPath: string;
    readonly snapshotPath: string;
    readonly initialPromptDelivered: boolean;
  };
}

interface YamlLine { readonly indent: number; readonly text: string; }

function stripComment(line: string): string {
  let quote: string | undefined;
  for (let index = 0; index < line.length; index++) {
    const char = line[index]!;
    if (quote) { if (char === quote) quote = undefined; continue; }
    if (char === "\"" || char === "'") quote = char;
    else if (char === "#" && (index === 0 || /\s/.test(line[index - 1]!))) return line.slice(0, index);
  }
  return line;
}

function scalar(raw: string): unknown {
  const text = raw.trim();
  if (text === "" || text === "~" || text === "null") return null;
  if (text === "true") return true;
  if (text === "false") return false;
  if (text === "{}") return {};
  if (text === "[]") return [];
  if (text.startsWith("\"")) { try { return JSON.parse(text); } catch { return text; } }
  if (text.startsWith("'") && text.endsWith("'") && text.length >= 2) return text.slice(1, -1).replace(/''/g, "'");
  if (text.startsWith("[") && text.endsWith("]")) return text.slice(1, -1).split(",").map(item => scalar(item)).filter(item => item !== null);
  if (/^-?\d+(\.\d+)?$/.test(text)) return Number(text);
  return text;
}

const isSequenceItem = (text: string) => text === "-" || text.startsWith("- ");
const KEY = /^("(?:[^"\\]|\\.)*"|'[^']*'|[^"'\s\[{][^:]*?):(?:\s+(.*))?$/;

/** Parses a block sequence or mapping whose first line sits at `indent`. Unsupported constructs degrade to strings. */
function parseBlock(lines: YamlLine[], start: number, indent: number): [unknown, number] {
  if (start >= lines.length) return [null, start];
  if (isSequenceItem(lines[start]!.text)) {
    const items: unknown[] = [];
    let index = start;
    while (index < lines.length && lines[index]!.indent === indent && isSequenceItem(lines[index]!.text)) {
      const rest = lines[index]!.text.slice(1).trimStart();
      if (rest === "") {
        const next = lines[index + 1];
        if (next && next.indent > indent) { const [value, after] = parseBlock(lines, index + 1, next.indent); items.push(value); index = after; }
        else { items.push(null); index++; }
      } else if (KEY.test(rest)) {
        // `- key: value` opens a mapping whose remaining keys align with `key`.
        const childIndent = indent + (lines[index]!.text.length - rest.length);
        lines[index] = { indent: childIndent, text: rest };
        const [value, after] = parseBlock(lines, index, childIndent);
        items.push(value); index = after;
      } else {
        items.push(scalar(rest)); index++;
        while (index < lines.length && lines[index]!.indent > indent) index++;
      }
    }
    return [items, index];
  }
  const result: Record<string, unknown> = {};
  let index = start;
  while (index < lines.length && lines[index]!.indent === indent && !isSequenceItem(lines[index]!.text)) {
    const match = KEY.exec(lines[index]!.text);
    if (!match) { index++; while (index < lines.length && lines[index]!.indent > indent) index++; continue; }
    const key = String(scalar(match[1]!));
    const value = match[2]?.trim() ?? "";
    index++;
    if (value !== "") {
      result[key] = scalar(value);
      // Block scalars (`|`, `>`) and other unsupported continuations are skipped, never mistaken for siblings.
      while (index < lines.length && lines[index]!.indent > indent) index++;
      continue;
    }
    const next = lines[index];
    if (next && (next.indent > indent || (next.indent === indent && isSequenceItem(next.text)))) {
      const [child, after] = parseBlock(lines, index, next.indent);
      result[key] = child; index = after;
    } else result[key] = null;
  }
  // Skip deeper lines that this subset could not attribute (e.g. block scalars).
  while (index < lines.length && lines[index]!.indent > indent) index++;
  return [result, index];
}

/**
 * Minimal parser for the `.bflow/config.yml` subset needed here (`environment.roles`, `environment.defaults`).
 * Runtime deliberately has no YAML dependency; JSON configuration is accepted verbatim.
 */
export function parseSosConfigDocument(source: string): unknown {
  try { return JSON.parse(source); } catch { /* YAML subset below */ }
  const lines: YamlLine[] = [];
  for (const raw of source.split(/\r?\n/)) {
    const text = stripComment(raw).replace(/\s+$/, "");
    if (!text.trim() || text.trim() === "---") continue;
    lines.push({ indent: text.length - text.trimStart().length, text: text.trimStart() });
  }
  return lines.length ? parseBlock(lines, 0, lines[0]!.indent)[0] : null;
}

function object(value: unknown): Record<string, unknown> | undefined {
  return typeof value === "object" && value !== null && !Array.isArray(value) ? value as Record<string, unknown> : undefined;
}
const text = (value: unknown) => typeof value === "string" && value.trim() ? value.trim() : undefined;
const provider = (value: unknown): SosProvider | undefined => SOS_PROVIDERS.find(item => item === value);

/** Reads `role: sos` from the repository configuration; a missing or unreadable entry inherits `defaultProvider`. */
export async function resolveSosRoleConfig(repositoryPath: string, defaultProvider: string): Promise<SosRoleConfig> {
  const fallback = provider(defaultProvider) ?? "claude";
  for (const file of CONFIG_FILES) {
    const configPath = join(repositoryPath, file);
    let source: string;
    try { source = await readFile(configPath, "utf8"); } catch { continue; }
    let environment: Record<string, unknown> | undefined;
    try { environment = object(object(parseSosConfigDocument(source))?.environment); } catch { environment = undefined; }
    const roles = Array.isArray(environment?.roles) ? environment.roles : [];
    const entry = roles.map(object).find(role => role?.role === "sos");
    if (!entry) return { provider: fallback, source: "default", configPath };
    const selected = provider(entry.cli) ?? fallback;
    const defaults = object(object(environment?.defaults)?.[selected]);
    const profileName = text(entry["profile-name"]) ?? text(defaults?.["profile-name"]);
    const model = text(entry.model), effort = text(entry.effort), fallbackCli = provider(entry.fallbackCli);
    return {
      provider: selected, source: "config", configPath,
      ...(model ? { model } : {}),
      // Agy encodes effort in the model name.
      ...(effort && selected !== "agy" ? { effort } : {}),
      ...(profileName ? { profileName } : {}),
      ...(fallbackCli && fallbackCli !== selected ? { fallbackCli } : {})
    };
  }
  return { provider: fallback, source: "default" };
}

/** Full-permission native arguments: SOS deliberately bypasses approvals/sandbox and carries no PreToolUse guard. */
export function buildSosProviderArguments(config: Pick<SosRoleConfig, "provider" | "model" | "effort">, repositoryPath: string, systemPromptPath: string): string[] {
  const { model, effort } = config;
  switch (config.provider) {
    case "codex":
      return ["--dangerously-bypass-approvals-and-sandbox", "-C", repositoryPath, "-c", "model_instructions_file=" + JSON.stringify(systemPromptPath),
        ...(model ? ["-m", model] : []), ...(effort ? ["-c", "model_reasoning_effort=" + JSON.stringify(effort)] : [])];
    case "claude":
      return ["--dangerously-skip-permissions", "--append-system-prompt-file", systemPromptPath,
        ...(model ? ["--model", model] : []), ...(effort ? ["--effort", effort] : [])];
    case "agy":
      return ["--workspace", repositoryPath, ...(model ? ["--model", model] : [])];
  }
}

function shell(value: string): string {
  return /^[A-Za-z0-9_./:@%+=-]+$/.test(value) ? value : `'${value.replace(/'/g, "'\\''")}'`;
}

function paneLine(pane: PaneBinding): string {
  return `- role=${pane.role} paneId=${pane.paneId} tabId=${pane.tabId} agentId=${pane.agentId} agentKind=${pane.agentKind} ` +
    `transportState=${pane.transportState} cwd=${pane.cwd}${pane.worktreePath ? ` worktreePath=${pane.worktreePath}` : ""}` +
    `${pane.session ? ` session=${pane.session.source}:${pane.session.value}` : ""}`;
}

function buildContext(options: SpawnSosAgentOptions, paths: { sosDirectory: string; snapshotPath: string; activityPath: string }): string {
  const herdr = `${shell(options.herdrBinary)} --session ${shell(options.sessionId)}`;
  const panes = options.manifest?.panes ?? [];
  const paneCommands = panes.flatMap(pane => [
    `# ${pane.role} (${pane.paneId})`,
    `${herdr} pane read ${shell(pane.paneId)} --source recent --lines 120`,
    `${herdr} pane process-info --pane ${shell(pane.paneId)}`
  ]);
  return [
    "## Hiện trường Bflow (BFLOWSOS)",
    "",
    `- HERDR_SESSION: ${options.sessionId}`,
    `- herdrBinary: ${options.herdrBinary}`,
    `- workspaceId: ${options.manifest?.herdrWorkspaceId ?? "(không có manifest)"}`,
    `- repositoryPath: ${options.repositoryPath}`,
    `- schedulerError: ${options.schedulerError ?? "(none)"}`,
    `- inboundError: ${options.inboundError ?? "(none)"}`,
    "",
    "### Pane đang chạy",
    ...(panes.length ? panes.map(paneLine) : ["- (manifest không có pane)"]),
    "",
    "### Lệnh Herdr dựng sẵn",
    "```sh",
    `${herdr} pane list`,
    `${herdr} agent list`,
    ...paneCommands,
    "```",
    "",
    "### Log và trạng thái",
    `- Herdr log: ${join(options.repositoryPath, ".bflow/logs/herdr.log")}`,
    `- Task activity: ${paths.activityPath}`,
    `- Pane state: ${join(options.repositoryPath, ".bflow/state/panes")}`,
    `- Host state directory: ${options.directory}`,
    `- Runtime snapshot: ${paths.snapshotPath}`,
    `- SOS directory: ${paths.sosDirectory}`
  ].join("\n");
}

