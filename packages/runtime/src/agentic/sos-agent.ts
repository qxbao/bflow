export function newSosAgentName(): string {
  return `bflow-sos-${randomBytes(3).toString("hex")}`;
}

/** Spawns the BFLOWSOS rescue agent in a new `SOS` tab with full context. Throws after recording a failure activity. */
export async function spawnSosAgent(options: SpawnSosAgentOptions): Promise<SpawnedSosAgentResult> {
  const config = await resolveSosRoleConfig(options.repositoryPath, options.defaultProvider);
  const agentName = options.agentName ?? newSosAgentName();
  const sosDirectory = join(options.directory, "sos");
  const snapshotPath = join(sosDirectory, "sos-runtime-snapshot.json");
  const contextPath = join(sosDirectory, "sos-context.md");
  const systemPromptPath = join(sosDirectory, "sos-system-prompt.md");
  try {
    await mkdir(sosDirectory, { recursive: true, mode: 0o700 });
    const recentActivity = await options.activityLog.read({ lines: 30 }).catch((error: unknown) => ({ unavailable: redactString(String(error)) }));
    await writeFile(snapshotPath, JSON.stringify({
      generatedAt: new Date().toISOString(), agentName,
      trigger: { messageId: options.turn.messageId, conversationSessionId: options.turn.conversationSessionId, userId: options.turn.userId },
      manifest: options.manifest ?? null, runtimeSnapshot: options.runtimeSnapshot ?? null,
      schedulerError: options.schedulerError ?? null, inboundError: options.inboundError ?? null,
      sosConfig: config, recentActivity
    }, null, 2) + "\n", { mode: 0o600 });
    const context = buildContext(options, { sosDirectory, snapshotPath, activityPath: options.activityLog.path });
    await writeFile(contextPath, `# BFLOWSOS context (${agentName})\n\n${context}\n`, { mode: 0o600 });
    await writeFile(systemPromptPath, `${SOS_INSTRUCTIONS}\n\n${context}\n`, { mode: 0o600 });

    const workspaceId = options.manifest?.herdrWorkspaceId;
    if (!workspaceId) throw new Error("No Herdr workspace is recorded in the session manifest; BFLOWSOS cannot open a tab");
    const created = JSON.parse(await options.herdr(["tab", "create", "--workspace", workspaceId, "--cwd", options.repositoryPath, "--label", "SOS", "--no-focus"])) as unknown;
    const result = object(object(created)?.result);
    const rootPane = object(result?.root_pane ?? result?.rootPane);
    const tab = object(result?.tab);
    const paneId = text(rootPane?.pane_id ?? rootPane?.paneId);
    const tabId = text(tab?.tab_id ?? tab?.tabId ?? rootPane?.tab_id ?? rootPane?.tabId);
    if (!paneId || !tabId) throw new Error("Herdr tab create returned no SOS tab/pane id");
    await options.herdr(["pane", "rename", paneId, agentName]);

    const start = (selected: SosProvider) => options.herdr(["agent", "start", agentName, "--kind", selected, "--pane", paneId, "--timeout", "60000", "--",
      // Model/effort belong to the configured primary CLI; a fallback CLI uses its own provider defaults.
      ...buildSosProviderArguments(selected === config.provider ? config : { provider: selected }, options.repositoryPath, systemPromptPath)]);
    let launched = config.provider;
    try { await start(config.provider); }
    catch (error) {
      if (!config.fallbackCli) throw error;
      launched = config.fallbackCli;
      await start(config.fallbackCli);
    }

    const initialPrompt = `BFLOWSOS: Bflow đang gặp sự cố. Đọc ${systemPromptPath}, ${contextPath} và ${snapshotPath}, ` +
      "dùng các lệnh herdr dựng sẵn để xem pane/log, tìm nguyên nhân gốc và sửa ngay, rồi báo cáo kết quả.";
    let initialPromptDelivered = false;
    try { await options.herdr(["agent", "prompt", paneId, initialPrompt]); initialPromptDelivered = true; }
    catch { /* Best effort: the agent already has the context files and system prompt. */ }

    await options.activityLog.record({ kind: "recovery", role: "sos", action: "sos_agent_spawned", outcome: "spawned",
      reason: `${agentName} (${launched}) in pane ${paneId}${initialPromptDelivered ? "" : "; initial prompt not delivered"}` });
    return { ok: true, value: { agentName, provider: launched, ...(config.model ? { model: config.model } : {}), tabId, paneId,
      sosDirectory, contextPath, systemPromptPath, snapshotPath, initialPromptDelivered } };
  } catch (error) {
    await options.activityLog.record({ kind: "recovery", role: "sos", action: "sos_agent_spawned", outcome: "failed",
      reason: redactString(String(error)).slice(0, 200) }).catch(() => false);
    throw error;
  }
}
